import { AURA_FPS, AURA_FRAMES, renderAura } from "./aura";
import { CLIP_ORDER, TIMING, type ClipKey3 } from "./clips";
import { ANCHOR, CAMERA, FRAME_H, FRAME_W, heroOf, NOMINAL_HEIGHT, poseAt, renderClipFrame, renderPose, type FrameResult, type Hero } from "./render";

/**
 * HERO RENDERER v3 as a SPRITE SET (`clank-v3`): a procedural set — no atlases, no manifest download. The same contract the arena, portraits
 * and cards already speak (clips with frames / fps / impact, a frame size, an anchor, a nominal height, left = mirrored right), but each hero's
 * strips are GENERATED from its own look on first use and cached by the compositor (48-hero LRU).
 *
 * Versioning: v1 (`clank-dev-v1`) and v2 (`clank-dev-v2`) stay shipped and selectable; v2 is what live battles were drawn with. A new art
 * version is a new set id, so every cache keyed on the set id (hero-card images, composed strips) re-keys by itself.
 */

export { V3_ART_REVISION, V3_SET_ID } from "./version";
import { V3_SET_ID } from "./version";

const row = (k: ClipKey3): number => CLIP_ORDER.indexOf(k);

function clipDefs(): Partial<Record<ClipKey, ClipDef>> {
  const out: Partial<Record<ClipKey, ClipDef>> = {};
  for (const k of CLIP_ORDER) {
    const t = TIMING[k];
    out[k as ClipKey] = {
      row: row(k), frames: t.frames, fps: t.fps, loop: t.loop,
      ...(t.impact !== undefined ? { impact: t.impact } : {}),
      ...(t.stride !== undefined ? { stride: t.stride } : {}),
      ...(t.refSpeed !== undefined ? { refSpeed: t.refSpeed } : {}),
    } as ClipDef;
  }
  return out;
}

let manifestCache: SpriteManifest | null = null;

/** The synthesized manifest (nothing in it points at an image: the set draws itself). */
export function v3Manifest(): SpriteManifest {
  if (manifestCache) return manifestCache;
  manifestCache = {
    spec: 2,
    id: V3_SET_ID,
    name: "Clank hero renderer v3 (procedural)",
    status: "production",
    credits: "Generated by the Clank RPG procedural hero engine (src/domain/sprites/v3).",
    pixelArt: true,
    frame: { w: FRAME_W, h: FRAME_H },
    anchor: { x: ANCHOR.x, y: ANCHOR.y },
    nominalHeightPx: NOMINAL_HEIGHT,
    images: {},
    clips: clipDefs(),
    directions: { right: { index: 0 }, left: { mirror: "right" } },
    layers: { "body.base": { z: 10, cells: {} } },
  } as SpriteManifest;
  return manifestCache;
}

/** What the compositor needs from a procedural hero. */
export interface ProceduralHero {
  hero: Hero;
  /** The archetype (stands in for a packed set's skeleton id). */
  rig: string;
  attackClip: "attack_slash" | "attack_thrust" | "attack_shoot";
  idleClip: "idle" | "idle2";
  /** Where shots leave on the attack's impact frame (frame px), for shooting weapons. */
  muzzle: { x: number; y: number } | null;
  /** Renders every frame of a clip (RGBA, frame-sized), in order. */
  frames(clip: ClipKey): FrameResult[];
  /** Renders ONE frame of a clip (RGBA, frame-sized) — the compositor generates strips a frame at a time. */
  frame(clip: ClipKey, f: number): Uint8ClampedArray;
  /** The rarity aura (a stored trait) as a looping strip of frames, or null when the hero has none. */
  aura: { id: string; frames: number; fps: number; render: () => Uint8ClampedArray[] } | null;
}

export interface ProceduralSet {
  id: string;
  hero(config: SpriteConfig, colors: readonly [string, string, string], rarity: string): ProceduralHero;
}

const SHOOTS = new Set(["bow", "staff", "tome"]);

/** A v3 clip for a contract clip key (anything this renderer does not draw falls back to idle). */
const clipOf = (clip: ClipKey): ClipKey3 => ((CLIP_ORDER as readonly string[]).includes(clip) ? (clip as ClipKey3) : "idle");

export function proceduralHero(config: SpriteConfig, colors: readonly [string, string, string], rarity: string): ProceduralHero {
  const hero = heroOf({ config, colors, rarity });
  const attackClip = hero.lo.attack;
  const imp = TIMING[attackClip].impact ?? 0;
  // where the shot leaves: measured on the impact pose the first time a shot needs it (not when the hero first appears)
  let muzzle: { x: number; y: number } | null | undefined = SHOOTS.has(hero.g.weapon) ? undefined : null;
  const muzzleOf = (): { x: number; y: number } | null => {
    if (muzzle !== undefined) return muzzle;
    const m = renderPose(hero, poseAt(hero, attackClip, imp), CAMERA).meta.muzzle;
    return (muzzle = m ? { x: m[0] + 0.5, y: m[1] + 0.5 } : null);
  };
  const auraKind = hero.g.aura;
  const aura = auraKind && ["ring", "sparks", "flame"].includes(auraKind)
    ? { id: `aura.${auraKind}`, frames: AURA_FRAMES, fps: AURA_FPS, render: () => Array.from({ length: AURA_FRAMES }, (_, f) => renderAura(auraKind, hero.g.colors.rarity, f)) }
    : null;
  return {
    hero,
    aura,
    rig: hero.g.arch,
    attackClip,
    idleClip: hero.g.stance === 1 ? "idle2" : "idle",
    get muzzle() {
      return muzzleOf();
    },
    frames(clip) {
      const k = clipOf(clip);
      const n = TIMING[k].frames;
      const out: FrameResult[] = [];
      for (let f = 0; f < n; f++) out.push(renderClipFrame(hero, k, f));
      return out;
    },
    frame(clip, f) {
      const k = clipOf(clip);
      return renderClipFrame(hero, k, Math.max(0, Math.min(TIMING[k].frames - 1, f))).rgba;
    },
  };
}

export const V3_SET: ProceduralSet = { id: V3_SET_ID, hero: proceduralHero };

/** A set that draws itself (no manifest file or atlases on disk): every catalogue item is generated, so nothing can be "missing". */
export const isProceduralSet = (id: string): boolean => id === V3_SET_ID;
